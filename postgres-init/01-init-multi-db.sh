#!/bin/bash
set -e

echo "=== Çoklu Veritabanı ve Kullanıcı Başlatma Betiği Devrede ==="

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    -- Guacamole DB & User
    SELECT 'CREATE USER $GUACAMOLE_DB_USER WITH PASSWORD '\''$GUACAMOLE_DB_PASSWORD'\'
    WHERE NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '$GUACAMOLE_DB_USER')\gexec

    SELECT 'CREATE DATABASE $GUACAMOLE_DB_NAME OWNER $GUACAMOLE_DB_USER'
    WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$GUACAMOLE_DB_NAME')\gexec

    GRANT ALL PRIVILEGES ON DATABASE $GUACAMOLE_DB_NAME TO $GUACAMOLE_DB_USER;

    -- Vaultwarden DB & User
    SELECT 'CREATE USER $VAULTWARDEN_DB_USER WITH PASSWORD '\''$VAULTWARDEN_DB_PASSWORD'\'
    WHERE NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '$VAULTWARDEN_DB_USER')\gexec

    SELECT 'CREATE DATABASE $VAULTWARDEN_DB_NAME OWNER $VAULTWARDEN_DB_USER'
    WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$VAULTWARDEN_DB_NAME')\gexec

    GRANT ALL PRIVILEGES ON DATABASE $VAULTWARDEN_DB_NAME TO $VAULTWARDEN_DB_USER;
EOSQL

echo "=== Çoklu Veritabanı Hazırlığı Tamamlandı ==="
